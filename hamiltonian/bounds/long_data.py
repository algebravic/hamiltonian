"""Generate doc/Papers/app_data.tex (Appendix C of the long version) from the data
files and fresh computations, so that no number is transcribed by hand.

    python -m hamiltonian.bounds.long_data            # full run (several minutes)
"""
from __future__ import annotations

import json
import math
import re
from math import lgamma, log
from pathlib import Path

import numpy as np

from .bethe import adjacency_sparse, bethe_value, sinkhorn_symmetric
from .bregman import B, log_upper_bound
from .edges import edges
from .hamp_predictor import dense_adjacency, log_hhat, sinkhorn
from .lift import lift, lift_moves
from .moves import check_move, check_separated
from .sinkhorn import constant_C
from .squares import is_ham_path, issq

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "data"
OUT = ROOT / "doc" / "Papers" / "app_data.tex"


def counts() -> dict[int, int]:
    return {int(a): int(b) for a, b in
            (l.split() for l in (DATA / "b071983.txt").read_text().splitlines() if l.strip())}


def wrap(seq, per_line=15) -> str:
    parts = [r"\ ".join(str(v) for v in seq[k:k + per_line]) for k in range(0, len(seq), per_line)]
    return r"\\ {}".join(parts)


def glue_items(glue, t):
    """Parse a glue list into items: ('g', v) or ('s', a, b); check junctions."""
    h = (t * t - 1) // 2
    items, k = [], 0
    while k < len(glue):
        if glue[k] <= h:
            items.append(("g", glue[k])); k += 1
        else:
            items.append(("s", glue[k], glue[k + 1])); k += 2
    for x, y in zip(items, items[1:]):
        assert issq(x[-1] + y[1]), (x, y)
    segs = [it for it in items if it[0] == "s"]
    assert len(segs) == t * t and len([i for i in items if i[0] == "g"]) == h
    return items


def glue_tex(items) -> str:
    toks = [str(it[1]) if it[0] == "g" else f"[{it[1]}\\ {it[2]}]" for it in items]
    lines, cur = [], []
    for tok in toks:
        cur.append(tok)
        if len(cur) == 12:
            lines.append(r"\ ".join(cur)); cur = []
    if cur:
        lines.append(r"\ ".join(cur))
    return r"\\ {}".join(lines)


def main() -> None:
    H = counts()
    tex = []
    w = tex.append
    w("% Generated by hamiltonian/bounds/long_data.py -- do not edit by hand.")
    w(r"\section{Data}\label{app:data}")
    w("All numbers in this appendix were produced by the procedures of \\cref{app:algorithms}; "
      "the certificates in \\cref{app:data-cert} can be checked by hand or by a short independent program.")

    # --- C.1 counts
    w(r"\subsection{Exact counts}\label{app:data-counts}")
    w(r"""\Cref{tab:counts} lists $\Ham(n)$, the number of undirected Hamiltonian paths of $G(n)$, for
$15\le n\le75$. Values for $n\le56$ were first obtained with Graphillion; the dynamic program of
\cref{alg:frontier} extended the computation to $n=75$.
For $n\le14$, $\Ham(n)=0$ since $G(n)$ is disconnected.""")
    ns = list(range(15, 76))
    rows = math.ceil(len(ns) / 3)
    w(r"\begin{table}[h]\centering\footnotesize")
    w(r"\begin{tabular}{rr@{\hspace{1.5em}}rr@{\hspace{1.5em}}rr}\toprule")
    w(r"$n$ & $\Ham(n)$ & $n$ & $\Ham(n)$ & $n$ & $\Ham(n)$\\\midrule")
    for r in range(rows):
        cells = []
        for c in range(3):
            k = r + c * rows
            cells += [str(ns[k]), str(H[ns[k]])] if k < len(ns) else ["", ""]
        w(" & ".join(cells) + r"\\")
    w(r"\bottomrule\end{tabular}")
    w(r"\caption{Exact values of $\Ham(n)$, $15\le n\le 75$. The value for $n=75$ is suspect; see \cref{subsec:barvinok}.}\label{tab:counts}")
    w(r"\end{table}")

    # --- C.2 certificates
    cert = json.loads((DATA / "bounds" / "certificate.json").read_text())
    glue = cert["glue"]
    w(r"\subsection{Certificates for \texorpdfstring{\cref{cor:seeds}}{the seeds}}\label{app:data-cert}")
    w(r"""Positions are numbered from $1$. A move is given by its window $[i,j]$ and the new content of
the window; all other positions are unchanged. Each move has been checked to be
parity-preserving (\cref{def:move}), and the moves of each seed are separated.""")
    lift_rows = []
    for s in cert["seeds"]:
        P, n0 = s["path"], len(s["path"])
        moves = [(m["i"], m["alt"]) for m in s["moves"]]
        assert is_ham_path(P, n0) and P[0] == 1 and P[-1] == 3
        for i, alt in moves:
            check_move(P, i, alt)
        check_separated(moves)
        w(rf"\paragraph{{Seed $n_0={n0}$, $k={len(moves)}$.}} The path is")
        w(r"\[\begin{array}{l}" + wrap(P) + r"\end{array}\]")
        for i, alt in moves:
            j = i + len(alt) - 1
            old = P[i:j + 1]
            w(rf"window $[{i + 1},{j + 1}]$ (anchors ${P[i - 1]}$ and ${P[j + 1]}$):")
            w(r"\[\begin{array}{rl}\text{old:}&\begin{array}[t]{@{}l@{}}" + wrap(old, 18)
              + r"\end{array}\\ \text{new:}&\begin{array}[t]{@{}l@{}}" + wrap(alt, 18)
              + r"\end{array}\end{array}\]")
        # lift two levels
        path, mv, n = P, moves, n0
        for level in (1, 2):
            new, offs = lift(path, glue)
            N = 25 * n + 12
            assert is_ham_path(new, N) and new[0] == 1 and new[-1] == 3
            mv = lift_moves(path, mv, offs)
            for i, alt in mv:
                check_move(new, i, alt)
            check_separated(mv)
            lift_rows.append((n0, level, N, len(mv)))
            path, n = new, N
    w(r"\begin{table}[h]\centering\small\begin{tabular}{rrrr}\toprule")
    w(r"seed $n_0$ & level $m$ & $N_m$ & separated moves verified\\\midrule")
    for r_ in lift_rows:
        w(" & ".join(str(x) for x in r_) + r"\\")
    w(r"\bottomrule\end{tabular}\caption{Explicit verification of \cref{thm:main} for $m=1,2$ (\cref{alg:certificate}).}\label{tab:liftcheck}\end{table}")

    # --- C.3 glue arrangements
    w(r"\subsection{Glue arrangements}\label{app:data-glue}")
    w(r"""Notation as in \cref{tab:glue}: a bracket $[x\ y]$ is a lifted segment traversed from $x$ to $y$, and
other entries are glue vertices. Every junction sum has been checked to be a square. The arrangement
of \cref{tab:glue} ($t=5$, $(u,w)=(1,3)$, $n$ odd) is the one used in \cref{thm:main}. The others
support \cref{prop:t3}.""")
    other = json.loads((DATA / "bounds" / "glue_other.json").read_text())
    for key, label in (("t5_u1_w3_even", r"$t=5$, $(u,w)=(1,3)$, $n$ even"),
                       ("t5_u1_w2_odd", r"$t=5$, $(u,w)=(1,2)$, $n$ odd"),
                       ("t5_u1_w2_even", r"$t=5$, $(u,w)=(1,2)$, $n$ even"),
                       ("t7_u1_w2_even", r"$t=7$, $(u,w)=(1,2)$, $n$ even")):
        t = int(key[1])
        items = glue_items(other[key], t)
        w(rf"\paragraph{{{label}.}}")
        w(r"{\small\[\begin{array}{l}" + glue_tex(items) + r"\end{array}\]}")
    glue_items(glue, 5)
    w(r"""For $t=3$ the exhaustive search (\cref{alg:glue} with exhaustive branching) finds no arrangement
in any of the $24$ cases $u\ne w\in\{1,2,3,4\}$, $n$ odd or even.""")

    # --- C.4 seed searches
    w(r"\subsection{Seed searches}\label{app:data-seeds}")
    def parse(fn):
        out = []
        for l in (DATA / "bounds" / fn).read_text().splitlines():
            m = re.match(r"n=(\d+) paths=(\d+) best k=(\d+)", l)
            if m:
                out.append(tuple(int(x) for x in m.groups()))
        return out
    ex, rnd = parse("seed_search_exhaustive.txt"), parse("seed_search_random.txt")
    w(r"\begin{table}[h]\centering\small")
    w(r"\begin{tabular}{rrr}\toprule $n$ & \#paths $1\to3$ & $k(n)$\\\midrule")
    for n, p, k in ex:
        w(f"{n} & {p} & {k}" + r"\\")
    w(r"\bottomrule\end{tabular}\qquad")
    w(r"\begin{tabular}{rrr}\toprule $n$ & samples & best $k$\\\midrule")
    for n, p, k in rnd:
        w(f"{n} & {p} & {k}" + r"\\")
    w(r"\bottomrule\end{tabular}")
    w(r"\caption{Left: exhaustive search over all Hamiltonian paths of $G(n)$ from $1$ to $3$ (odd $n\le41$), "
      r"giving the exact value of $k(n)$. Right: best $k$ among random samples (\cref{alg:seeds}; windows of "
      r"length $\le24$), so only a lower bound for $k(n)$.}\label{tab:seeds}\end{table}")

    # --- C.5 numerics
    w(r"\subsection{Numerical tables}\label{app:numerics}")
    w(r"\paragraph{The constant $C$ (\cref{alg:sinkhorn-cont}).}")
    vals = [(M, *constant_C(M)) for M in (400, 1600, 3200)]
    w(r"\[\begin{array}{rcc}M & C & \text{max residual}\\" +
      r"\\".join(f"{M} & {C:.7f} & {res:.1e}" for M, C, res in vals) + r"\end{array}\]")
    Cbest = vals[-1][1]
    w(rf"Also $B=\frac{{\sqrt2}}2-\frac32\log(1+\sqrt2)={B:.7f}$ and $\log\iint\kappa={log(4/3*(math.sqrt(2)-1)):.7f}$.")

    w(r"\paragraph{Edge counts (\cref{alg:edges}).}")
    c0 = 2 / 3 * (math.sqrt(2) - 1)
    erows = []
    for n in (10**4, 10**6, 10**8):
        e, e4 = edges(n), edges(n // 4)
        erows.append(f"10^{{{int(round(math.log10(n)))}}} & {e} & {e / n**1.5:.6f} & {e4 / (e / 16):.4f}")
    w(r"\[\begin{array}{rrcc}n & e(G(n)) & e/n^{3/2} & e(G(n)[4\mathbb{Z}])\big/\tfrac1{16}e(G(n))\\" +
      r"\\".join(erows) + rf"\end{{array}}\]with $\frac23(\sqrt2-1)={c0:.6f}$.")

    w(r"\paragraph{The finite Bregman bound (\cref{alg:bregman}).} Normalised value "
      r"$\bigl(\log\mathrm{UB}(n)-\log n!+\frac n2\log n\bigr)/n$, which tends to $B$ slowly:")
    brows = []
    for n in (25, 50, 75, 100, 1000, 10000):
        ub = log_upper_bound(n)
        brows.append(f"{n} & {ub:.2f} & {(ub - (lgamma(n + 1) - n / 2 * log(n))) / n:+.4f}")
    w(r"\[\begin{array}{rrr}n & \log\mathrm{UB}(n) & \text{normalised}\\" + r"\\".join(brows) + r"\end{array}\]")

    w(r"\paragraph{Bethe lower bound for cycle covers (\cref{alg:bethe}).}")
    bt = []
    for n in (1000, 4000, 16000, 64000):
        A = adjacency_sparse(n)
        x = sinkhorn_symmetric(A)
        import scipy.sparse as sp
        S = (sp.diags(x) @ A @ sp.diags(x)).tocsr()
        F = bethe_value(S)
        bt.append(f"{n} & {(F - n / 2 * log(n)) / n:+.5f}")
    w(r"\[\begin{array}{rc}n & (F(S)-\frac n2\log n)/n\\" + r"\\".join(bt) +
      rf"\\\infty & C-1={Cbest - 1:+.5f}\end{{array}}\]")

    w(r"\paragraph{Residuals (\cref{alg:predictor}).}")
    w(r"""$r_C(n)=\log\Ham(n)-[\log(n!/2)-\frac{n-1}2\log n+Cn]$ (the constant-$C$ formula of \cref{tab:resid})
and $r_S(n)=\log\Ham(n)-\log\widehat\Ham(n)$ (the scaling predictor of \cref{subsec:barvinok}). For
$n\le30$, $r_S$ is undefined, because the Sinkhorn scaling does not exist.""")
    res = []
    for n in sorted(H):
        if H[n] == 0:
            continue
        rC = log(H[n]) - (lgamma(n + 1) - log(2) - (n - 1) / 2 * log(n) + Cbest * n)
        rS = None
        if n >= 31:
            d = sinkhorn(dense_adjacency(n))
            rS = log(H[n]) - log_hhat(n, d)
        res.append((n, rC, rS))
    half = math.ceil(len(res) / 2)
    w(r"\begin{table}[h]\centering\footnotesize\begin{tabular}{rrr@{\hspace{2em}}rrr}\toprule")
    w(r"$n$ & $r_C$ & $r_S$ & $n$ & $r_C$ & $r_S$\\\midrule")
    def cell(t):
        n, rC, rS = t
        return f"{n} & {rC:+.2f} & " + ("---" if rS is None else f"{rS:+.2f}")
    for k in range(half):
        left = cell(res[k])
        right = cell(res[k + half]) if k + half < len(res) else " & & "
        w(left + " & " + right + r"\\")
    w(r"\bottomrule\end{tabular}\caption{Residuals of $\log\Ham(n)$.}\label{tab:residfull}\end{table}")

    OUT.write_text("\n".join(tex) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
